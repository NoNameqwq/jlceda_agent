export function buildSkillsPrompt(ids: string[] | undefined): string {
	if (!ids?.length)
		return '';
	const selected = BUILTIN_SKILLS.filter(s => ids.includes(s.id));
	if (!selected.length)
		return '';
	return `# 用户已挂载的技能（任务匹配时主动遵循）\n以下规则与基础提示词同等有效；只使用本扩展已有工具，不调用技能来源项目的 CLI 或脚本。\n\n${selected.map(s => s.prompt).join('\n\n')}`;
}
