function esc(v: string): string {
	return v.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** 解析单行 XML 元素的属性 */
export function parseAttrs(line: string): Record<string, string> {
	const out: Record<string, string> = {};
	const re = /([A-Z_][\w.:-]*)="([^"]*)"/gi;
	let m: RegExpExecArray | null = re.exec(line);
	while (m) {
		out[m[1]] = m[2];
		m = re.exec(line);
	}
	return out;
}

/** 解析 .package 文件的引脚（按文件顺序 = 物理引脚 1..N） */
export function parsePackagePins(xml: string): Array<{ id: string; label: string; type: string }> {
	const pins: Array<{ id: string; label: string; type: string }> = [];
	const re = /<pin\b[^>]*>/g;
	let m: RegExpExecArray | null = re.exec(xml);
	while (m) {
		const a = parseAttrs(m[0]);
		pins.push({ id: a.id ?? '', label: (a.label ?? a.id ?? '').trim(), type: a.type ?? '' });
		m = re.exec(xml);
	}
	return pins;
}

// ———————————————————————— 校验与生成 ————————————————————————

export function validatePins(pins: SimPinDef[]): string[] {
	const errs: string[] = [];
	if (!Array.isArray(pins) || pins.length < 2)
		return ['至少需要 2 个引脚'];
	if (pins.length > 128)
		errs.push('引脚数不能超过 128');
	const nums = new Set<number>();
	const ids = new Set<string>();
	for (const p of pins) {
		if (!Number.isInteger(p.number) || p.number < 1)
			errs.push(`引脚编号无效：${p.number}`);
		else if (nums.has(p.number))
			errs.push(`引脚编号重复：${p.number}`);
		nums.add(p.number);
		if (!PIN_ID_RE.test(p.id ?? ''))
			errs.push(`引脚 ID 只能含字母、数字、下划线：「${p.id}」`);
		else if (ids.has(p.id))
			errs.push(`引脚 ID 重复：${p.id}`);
		ids.add(p.id);
	}
	const sorted = [...nums].sort((a, b) => a - b);
	if (sorted.length && sorted[sorted.length - 1] !== sorted.length)
		errs.push(`引脚编号需从 1 连续编号到 ${pins.length}`);
	return errs;
}

/** 生成封装文件：DIP 布局，宽 4 格，左侧自上而下、右侧自下而上 */
export function buildPackage(def: Pick<CustomSimComponent, 'name' | 'pins'>): string {
	const pins = [...def.pins].sort((a, b) => a.number - b.number);
	const n = pins.length;
	const half = Math.ceil(n / 2);
	const left = pins.filter(p => (p.side ?? (p.number <= half ? 'left' : 'right')) === 'left');
	const right = pins.filter(p => !left.includes(p));
	const rows = Math.max(left.length, right.length);
	const height = rows + 1;
	const lines: string[] = [];
	// 物理顺序写出（SimulIDE 以文件顺序作为 packagePin 序号）
	for (const p of pins) {
		const isLeft = left.includes(p);
		const idx = isLeft ? left.indexOf(p) : right.length - 1 - right.indexOf(p);
		const y = (idx + 1) * 8 + (isLeft ? 0 : (rows - right.length) * 8);
		lines.push(`    <pin type="${esc(p.type ?? '')}" xpos="${isLeft ? -8 : 40}" ypos="${y}" angle="${isLeft ? 180 : 0}" length="8" id="${esc(p.id)}" label="${esc(p.label ?? p.id)}" /><!-- packagePin${p.number} -->`);
	}
	return `<!DOCTYPE SimulIDE>\n\n<!-- Generated by EDA Agent -->\n\n<packageB name="${esc(def.name)}" pins="${n}" width="4" height="${height}" background="" type="Logic" >\n\n${lines.join('\n')}\n    \n</packageB>\n`;
}

const GATE_ITEM: Record<SimGateType, { itemtype: string; inverted: boolean; maxInputs: number; minInputs: number }> = {
	and: { itemtype: 'And Gate', inverted: false, maxInputs: 16, minInputs: 2 },
	nand: { itemtype: 'And Gate', inverted: true, maxInputs: 16, minInputs: 2 },
	or: { itemtype: 'Or Gate', inverted: false, maxInputs: 16, minInputs: 2 },
	nor: { itemtype: 'Or Gate', inverted: true, maxInputs: 16, minInputs: 2 },
	xor: { itemtype: 'Xor Gate', inverted: false, maxInputs: 2, minInputs: 2 },
	xnor: { itemtype: 'Xor Gate', inverted: true, maxInputs: 2, minInputs: 2 },
	buffer: { itemtype: 'Buffer', inverted: false, maxInputs: 1, minInputs: 1 },
	not: { itemtype: 'Buffer', inverted: true, maxInputs: 1, minInputs: 1 },
};

const COMMON = 'mainComp="false" Show_id="false" Show_Val="false" Pos="0,0" rotation="0" hflip="1" vflip="1" idLabPos="-16,-24" labelrot="0" valLabPos="0,0" valLabRot="0"';
const LOGIC_IO = 'Input_High_V="2.5 V" Input_Low_V="2.5 V" Input_Imped="1e+14 Ω" Out_High_V="5 V" Out_Low_V="0 V" Out_Imped="40 Ω" rndPD="false"';

function isConst(net: string): 'HIGH' | 'LOW' | undefined {
	const u = net.trim().toUpperCase();
	if (u === 'HIGH' || u === '1' || u === 'VCC_CONST')
		return 'HIGH';
	if (u === 'LOW' || u === '0' || u === 'GND_CONST')
		return 'LOW';
	return undefined;
}

/** 由逻辑门描述生成子电路：每个门脚接一个同名 Tunnel，同名 Tunnel 自动相连 */
export function buildGateCircuit(pins: SimPinDef[], gates: SimGateDef[]): { circuit: string; errors: string[]; warnings: string[] } {
	const errors: string[] = [];
	const warnings: string[] = [];
	const pinIds = new Set(pins.map(p => p.id));
	const driven = new Map<string, number>();
	const used = new Set<string>();
	const items: string[] = [];
	const cons: string[] = [];
	let seq = 1;
	let conSeq = 1;
	const tunnel = (net: string, out: boolean): string => {
		const id = `Tunnel-${seq++}`;
		items.push(`<item itemtype="Tunnel" CircId="${id}" ${COMMON.replace('hflip="1"', `hflip="${out ? -1 : 1}"`)} label="${id}" Name="${esc(net)}" />`);
		return `${id}-pin`;
	};
	const constant = (level: 'HIGH' | 'LOW'): string => {
		const id = `Fixed Voltage-${seq++}`;
		items.push(`<item itemtype="Fixed Voltage" CircId="${id}" ${COMMON} label="${id}" Out="${level === 'HIGH'}" Voltage="5 V" />`);
		return `${id}-outnod`;
	};
	const connect = (a: string, b: string) => cons.push(`<item itemtype="Connector" uid="connector-${conSeq++}" startpinid="${a}" endpinid="${b}" pointList="0,0,0,0" />`);

	if (!gates?.length)
		errors.push('gates 不能为空');
	for (const [gi, g] of (gates ?? []).entries()) {
		const spec = GATE_ITEM[g.type];
		if (!spec) {
			errors.push(`第 ${gi + 1} 个门：不支持的类型 ${g.type}（可用 ${Object.keys(GATE_ITEM).join('/')}）`);
			continue;
		}
		const ins = (g.inputs ?? []).map(String);
		if (ins.length < spec.minInputs || ins.length > spec.maxInputs) {
			errors.push(`第 ${gi + 1} 个门（${g.type}）输入数应为 ${spec.minInputs === spec.maxInputs ? spec.minInputs : `${spec.minInputs}~${spec.maxInputs}`}，实际 ${ins.length}${g.type.includes('xor') ? '；多输入异或请级联多个 xor' : ''}`);
			continue;
		}
		if (!g.output || !PIN_ID_RE.test(g.output) || isConst(g.output)) {
			errors.push(`第 ${gi + 1} 个门：输出网络名无效「${g.output}」`);
			continue;
		}
		for (const n of [...ins, g.output]) {
			if (!isConst(n) && !PIN_ID_RE.test(n))
				errors.push(`第 ${gi + 1} 个门：网络名只能含字母数字下划线「${n}」`);
		}
		driven.set(g.output, (driven.get(g.output) ?? 0) + 1);
		const gid = `${spec.itemtype}-${seq++}`;
		const tpd = Math.max(1, Math.round((g.tpd_ns ?? 10) * 1000));
		const numIn = spec.itemtype === 'And Gate' || spec.itemtype === 'Or Gate' ? ` Num_Inputs="${ins.length} _Inputs"` : '';
		const tri = spec.itemtype === 'Buffer' ? ' Tristate="false"' : '';
		items.push(`<item itemtype="${spec.itemtype}" CircId="${gid}" ${COMMON} label="${gid}"${numIn}${tri} Inverted="${spec.inverted}" Open_Collector="${!!g.open_collector}" ${LOGIC_IO} Tpd_ps="${tpd} ps" Tr_ps="3000 ps" Tf_ps="4000 ps" />`);
		ins.forEach((n, i) => {
			const c = isConst(n);
			connect(c ? constant(c) : tunnel(n, false), `${gid}-in${i}`);
			if (!c)
				used.add(n);
		});
		connect(tunnel(g.output, true), `${gid}-out`);
	}
	for (const [net, n] of driven) {
		if (n > 1)
			errors.push(`网络 ${net} 被 ${n} 个门同时驱动`);
	}
	for (const n of used) {
		if (!pinIds.has(n) && !driven.has(n))
			warnings.push(`内部网络 ${n} 没有任何门驱动（悬空）`);
	}
	for (const p of pins) {
		if (p.type === 'unused')
			continue;
		if (!used.has(p.id) && !driven.has(p.id))
			warnings.push(`引脚 ${p.number}（${p.id}）未接入内部电路；电源 / NC 引脚请设 type: "unused"`);
	}
	const circuit = `${HEADER}\n\n${[...items, ...cons].join('\n\n')}\n\n</circuit>\n`;
	return { circuit, errors, warnings };
}

/** 自定义元件清单（SimulIDE ComponentSelector 读取 /config/data/*.xml） */
export function buildRegistryXml(list: CustomSimComponent[]): string {
	const items = list.map(c => `    <item name="${esc(c.name)}" info="${esc(c.info ?? 'EDA Agent custom')}" ></item>`).join('\n');
	return `<!DOCTYPE SimulIDE>\n\n<itemlib>\n  <itemset category="EDA Agent/Custom" type="Subcircuit" folder="ICs">\n${items}\n  </itemset>\n</itemlib>\n`;
}

/**
 * 真值表测试台：每个测试向量放一个独立的元件实例，输入接固定电压源（高 5V / 低 0V），
 * 每个输出引脚放一个电压探针。一次加载即可得到全部向量的结果。
 */
export function buildTestBench(def: CustomSimComponent, vectors: TruthVector[], outputs: string[], probeBase: number): { circuit: string; probes: Array<{ key: string; vector: number; pin: string }> } {
	const items: string[] = [];
	const probes: Array<{ key: string; vector: number; pin: string }> = [];
	let seq = 1000;
	let conSeq = 1;
	let probeSeq = probeBase;
	vectors.forEach((v, i) => {
		const cid = `${def.name}-${i + 1}`;
		items.push(`<item itemtype="Subcircuit" CircId="${cid}" ${COMMON} label="U${i + 1}" Logic_Symbol="false" />`);
		for (const [pin, val] of Object.entries(v.inputs ?? {})) {
			const vid = `Fixed Voltage-${seq++}`;
			items.push(`<item itemtype="Fixed Voltage" CircId="${vid}" ${COMMON} label="${vid}" Out="${!!Number(val)}" Voltage="5 V" />`);
			items.push(`<item itemtype="Connector" uid="Connector-${conSeq++}" startpinid="${vid}-outnod" endpinid="${cid}-${pin}" pointList="0,0,0,0" />`);
		}
		for (const pin of outputs) {
			const pid = `Probe-${probeSeq++}`;
			items.push(`<item itemtype="Probe" CircId="${pid}" ${COMMON} label="${pid}" ShowVolt="true" Threshold="2.5 V" voltMes="${cid}-${pin}" />`);
			probes.push({ key: `${pid}-${cid}-${pin}`, vector: i, pin });
		}
	});
	return { circuit: `${HEADER}\n\n${items.join('\n\n')}\n\n</circuit>\n`, probes };
}

/** 枚举真值表：给定输入引脚，生成全部 2^n 组合（n ≤ 6） */
export function exhaustiveVectors(inputs: string[]): TruthVector[] {
	const n = inputs.length;
	const out: TruthVector[] = [];
	for (let m = 0; m < 2 ** n; m++) {
		const v: Record<string, number> = {};
		inputs.forEach((p, i) => {
			v[p] = (m >> (n - 1 - i)) & 1;
		});
		out.push({ inputs: v });
	}
	return out;
}

