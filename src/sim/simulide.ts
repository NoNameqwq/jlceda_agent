// ———————————————————————— 类型 ————————————————————————

export interface SimPinDef {
	/** 引脚编号（1 起，对应芯片物理引脚） */
	number: number;
	/** 引脚 ID：子电路内同名 Tunnel 与之相连；只能含字母数字下划线 */
	id: string;
	label?: string;
	/** 左 / 右侧；缺省按 DIP 排列（前一半在左，后一半在右） */
	side?: 'left' | 'right';
	/** '' 普通；'unused' 不参与仿真（电源 / NC）；'inverted' 显示反相圈 */
	type?: '' | 'unused' | 'inverted';
}

export type SimGateType = 'and' | 'nand' | 'or' | 'nor' | 'xor' | 'xnor' | 'buffer' | 'not';

export interface SimGateDef {
	type: SimGateType;
	/** 输入网络名：引脚 ID、内部网络名，或常量 HIGH / LOW */
	inputs: string[];
	/** 输出网络名 */
	output: string;
	open_collector?: boolean;
	/** 传播延时（ns），默认 10 */
	tpd_ns?: number;
}

export interface CustomSimComponent {
	name: string;
	info?: string;
	pins: SimPinDef[];
	/** 子电路正文（.sim1） */
	circuit: string;
	source: 'gates' | 'raw';
	gates?: SimGateDef[];
	/** 推荐的外壳芯片（引脚数相同的内置子电路，用于在 EDA 中放置后绑定） */
	shell?: string;
	createdAt: number;
	updatedAt: number;
	/** 最近一次真值表测试结果 */
	lastTest?: { passed: number; total: number; at: number };
}

export interface TruthVector {
	inputs: Record<string, number | boolean>;
	expect?: Record<string, number | boolean>;
}

