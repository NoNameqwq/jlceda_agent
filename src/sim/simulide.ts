export const SIM_STATE: Record<number, string> = { 0: 'stopped', 1: 'error', 2: 'starting', 3: 'paused', 4: 'waiting', 5: 'running', 6: 'debug' };

export interface SeriesStat { last: number | string; min?: number; max?: number; samples: number; lastTime: number }

/** 累积 getSimulationData 的增量数据 */
export function accumulate(stats: Map<string, SeriesStat>, json: string): void {
	if (!json || json.length < 3)
		return;
	let obj: Record<string, Array<[number, number | string]>>;
	try {
		obj = JSON.parse(json);
	}
	catch {
		return;
	}
	for (const [k, arr] of Object.entries(obj)) {
		if (!Array.isArray(arr) || !arr.length)
			continue;
		const s = stats.get(k) ?? { last: 0, samples: 0, lastTime: 0 };
		for (const pt of arr) {
			if (!Array.isArray(pt))
				continue;
			const [t, v] = pt;
			s.samples++;
			s.last = v;
			s.lastTime = Number(t) || s.lastTime;
			if (typeof v === 'number') {
				s.min = s.min === undefined ? v : Math.min(s.min, v);
				s.max = s.max === undefined ? v : Math.max(s.max, v);
			}
		}
		stats.set(k, s);
	}
}

export class SimEngine {
	readonly logs: string[];
	private installed = new Set<string>();

	private constructor(readonly M: SimModule, logs: string[]) {
		this.logs = logs;
	}

	static async create(factory: SimFactory, wasm: { binary?: Uint8Array; module?: WebAssembly.Module }, verbose = false): Promise<SimEngine> {
		const logs: string[] = [];
		const push = (s: unknown) => {
			logs.push(String(s));
			if (logs.length > 600)
				logs.splice(0, logs.length - 600);
			if (verbose)
				console.debug('[SimulIDE]', s);
		};
		const opts: any = { print: push, printErr: (s: unknown) => push(`E: ${String(s)}`), locateFile: (p: string) => p };
		if (wasm.module) {
			const mod = wasm.module;
			opts.instantiateWasm = (imports: WebAssembly.Imports, done: (inst: WebAssembly.Instance, m: WebAssembly.Module) => void) => {
				WebAssembly.instantiate(mod, imports).then(inst => done(inst, mod), (e) => {
					push(`E: instantiate failed ${String(e)}`);
				});
				return {};
			};
		}
		else {
			opts.wasmBinary = wasm.binary;
		}
		const M = await factory(opts);
		return new SimEngine(M, logs);
	}

	version(): string {
		try {
			return String(this.M.ccall('getVersion', 'string', [], []));
		}
		catch {
			return 'unknown';
		}
	}

	/** 把自定义元件写入引擎虚拟文件系统（必须在 load 之前调用） */
	installCustom(list: CustomSimComponent[]): void {
		const FS = this.M.FS;
		for (const name of this.installed) {
			const dir = `${CUSTOM_DIR}/${name}`;
			for (const f of [`${name}.package`, `${name}.sim1`]) {
				try {
					FS.unlink(`${dir}/${f}`);
				}
				catch {}
			}
			try {
				FS.rmdir(dir);
			}
			catch {}
		}
		this.installed.clear();
		try {
			FS.unlink(REGISTRY_XML);
		}
		catch {}
		if (!list.length)
			return;
		for (const c of list) {
			const dir = `${CUSTOM_DIR}/${c.name}`;
			FS.mkdirTree(dir);
			FS.writeFile(`${dir}/${c.name}.package`, buildPackage(c));
			FS.writeFile(`${dir}/${c.name}.sim1`, c.circuit);
			this.installed.add(c.name);
		}
		FS.writeFile(REGISTRY_XML, buildRegistryXml(list));
	}

	load(text: string, fileName = 'circuit.sim1'): number {
		return Number(this.M.ccall('loadCircuitFromFile', 'number', ['string', 'string'], [fileName, text]));
	}

	start(): void {
		this.M._startSimulation();
	}

	stop(): void {
		this.M._stopSimulation();
	}

	pause(): void {
		this.M._pauseSimulation();
	}

	resume(): void {
		this.M._resumeSimulation();
	}

	setSpeed(v: number): void {
		this.M._setSimulationSpeed(v);
	}

	step(): void {
		this.M._stepSimulation();
	}

	state(): number {
		return this.M._getSimulationState();
	}

	time(): number {
		return this.M._getSimulationTime();
	}

	data(): string {
		return String(this.M.ccall('getSimulationData', 'string', [], []) ?? '{}');
	}

	update(id: string, attr: string, value: string): boolean {
		return !!this.M.ccall('updateCircuitData', 'number', ['string', 'string', 'string'], [id, attr, value]);
	}

	readFile(path: string): string | undefined {
		try {
			return this.M.FS.readFile(path, { encoding: 'utf8' });
		}
		catch {
			return undefined;
		}
	}

	errorLogs(limit = 30): string[] {
		return this.logs.filter(l => /^E:|ERROR|Error|error|not found|No .* found|Not Converging|does not exist|Cannot/i.test(l)).slice(-limit);
	}

	/** 离线运行：加载 → 运行 steps 步（每步默认 1µs 仿真时间）→ 汇总数据 */
	run(text: string, steps: number): { load: number; state: string; timePs: number; stats: Map<string, SeriesStat>; errors: string[] } {
		this.logs.length = 0;
		const stats = new Map<string, SeriesStat>();
		const load = this.load(text);
		if (load !== 0)
			return { load, state: 'error', timePs: 0, stats, errors: this.errorLogs() };
		this.start();
		const n = Math.max(1, Math.min(20000, Math.round(steps)));
		for (let i = 0; i < n; i++) {
			this.step();
			if (i % 20 === 19)
				accumulate(stats, this.data());
			if (this.state() !== 5)
				break;
		}
		accumulate(stats, this.data());
		const st = SIM_STATE[this.state()] ?? String(this.state());
		const timePs = this.time();
		try {
			this.stop();
		}
		catch {}
		return { load, state: st, timePs, stats, errors: this.errorLogs() };
	}

	// —— 内置元件库 ——
	private builtinCache?: Array<{ name: string; info: string; category: string; type: string; folder: string; xml: string }>;

	listBuiltin(): Array<{ name: string; info: string; category: string; type: string; folder: string; xml: string }> {
		if (this.builtinCache)
			return this.builtinCache;
		const out: Array<{ name: string; info: string; category: string; type: string; folder: string; xml: string }> = [];
		let files: string[] = [];
		try {
			files = (this.M.FS.readdir('/config/data') as string[]).filter(f => f.endsWith('.xml') && `/config/data/${f}` !== REGISTRY_XML);
		}
		catch {}
		for (const f of files) {
			// 自闭合的 <itemset .../> 只声明分类，去掉以免吞掉下一个 itemset 的属性
			const xml = (this.readFile(`/config/data/${f}`) ?? '').replace(/<itemset\b[^>]*\/>/g, '');
			const setRe = /<itemset\b([^>]*)>([\s\S]*?)<\/itemset>/g;
			let m: RegExpExecArray | null = setRe.exec(xml);
			while (m) {
				const sa = parseAttrs(m[1]);
				const itemRe = /<item\b([^>]*)>/g;
				let im: RegExpExecArray | null = itemRe.exec(m[2]);
				while (im) {
					const ia = parseAttrs(im[1]);
					if (ia.name)
						out.push({ name: ia.name, info: (ia.info ?? '').trim(), category: sa.category ?? '', type: ia.type ?? sa.type ?? '', folder: ia.folder ?? sa.folder ?? '', xml: f });
					im = itemRe.exec(m[2]);
				}
				m = setRe.exec(xml);
			}
		}
		this.builtinCache = out;
		return out;
	}

	/** 内置子电路的封装引脚（按物理顺序） */
	builtinPins(name: string): Array<{ id: string; label: string; type: string }> | undefined {
		const it = this.listBuiltin().find(x => x.name.toUpperCase() === name.toUpperCase());
		const folder = it?.folder || 'ICs';
		const n = it?.name ?? name;
		const xml = this.readFile(`/config/data/${folder}/${n}/${n}.package`) ?? this.readFile(`/config/data/${folder}/${n}/${n}_LS.package`);
		return xml ? parsePackagePins(xml) : undefined;
	}

	/** 内置子电路的电路文件（.sim1），供 Agent 参考实现方式 */
	builtinCircuit(name: string, maxLen = 20_000): string | undefined {
		const it = this.listBuiltin().find(x => x.name.toUpperCase() === name.toUpperCase());
		const folder = it?.folder ?? 'ICs';
		const n = it?.name ?? name;
		const s = this.readFile(`/config/data/${folder}/${n}/${n}.sim1`);
		return s && s.length > maxLen ? `${s.slice(0, maxLen)}\n<!-- 已截断 -->` : s;
	}

	/** 引脚数相同的内置子电路（作为 EDA 中放置的外壳） */
	shellCandidates(pinCount: number, limit = 6): string[] {
		const pref = ['74HC00', '74HC02', '74HC04', '74HC08', '74HC32', '74HC86', '74HC74', '74HC138', '74HC595', '74HC245'];
		const ok: string[] = [];
		for (const name of pref) {
			const pins = this.builtinPins(name);
			if (pins?.length === pinCount)
				ok.push(name);
		}
		if (ok.length < limit) {
			for (const it of this.listBuiltin()) {
				if (ok.length >= limit)
					break;
				if (it.type !== 'Subcircuit' || ok.includes(it.name) || !/^74|^CD/i.test(it.name))
					continue;
				const pins = this.builtinPins(it.name);
				if (pins?.length === pinCount)
					ok.push(it.name);
			}
		}
		return ok.slice(0, limit);
	}
}

// ———————————————————————— 真值表测试 ————————————————————————

export interface TruthRow {
	inputs: Record<string, number>;
	outputs: Record<string, { volt: number | undefined; logic: 0 | 1 | 'X' }>;
	expect?: Record<string, number>;
	pass?: boolean;
}

export interface TruthResult {
	rows: TruthRow[];
	passed: number;
	checked: number;
	total: number;
	errors: string[];
	simTimeUs: number;
}

type Logic = 0 | 1 | 'X';

/** 在 JS 中按门描述求值（组合逻辑；含反馈时迭代至稳定，无法确定的为 X），用于生成期望值 */
export function evalGates(gates: SimGateDef[], inputs: Record<string, number>): Record<string, Logic> {
	const val = new Map<string, Logic>();
	for (const [k, v] of Object.entries(inputs))
		val.set(k, Number(v) ? 1 : 0);
	const get = (n: string): Logic => {
		const c = isConst(n);
		if (c)
			return c === 'HIGH' ? 1 : 0;
		return val.get(n) ?? 'X';
	};
	const inv = (x: Logic): Logic => (x === 'X' ? 'X' : x ? 0 : 1);
	for (let iter = 0; iter < gates.length + 4; iter++) {
		let changed = false;
		for (const g of gates) {
			const ins = (g.inputs ?? []).map(get);
			let out: Logic;
			switch (g.type) {
				case 'and': case 'nand':
					out = ins.includes(0) ? 0 : ins.includes('X') ? 'X' : 1;
					break;
				case 'or': case 'nor':
					out = ins.includes(1) ? 1 : ins.includes('X') ? 'X' : 0;
					break;
				case 'xor': case 'xnor':
					out = ins.includes('X') ? 'X' : ((ins as number[]).reduce((a, b) => a ^ b, 0) as 0 | 1);
					break;
				default:
					out = ins[0] ?? 'X';
			}
			if (g.type === 'nand' || g.type === 'nor' || g.type === 'xnor' || g.type === 'not')
				out = inv(out);
			if (val.get(g.output) !== out) {
				val.set(g.output, out);
				changed = true;
			}
		}
		if (!changed)
			break;
	}
	return Object.fromEntries(val);
}

/** 自动测试向量：≤ 6 个输入穷举；否则全 1、全 0、逐位置 0、逐位置 1 */
export function autoVectors(inputs: string[]): TruthVector[] {
	if (inputs.length <= 6)
		return exhaustiveVectors(inputs);
	const all = (v: number) => Object.fromEntries(inputs.map(p => [p, v]));
	const out: TruthVector[] = [{ inputs: all(1) }, { inputs: all(0) }];
	for (const p of inputs)
		out.push({ inputs: { ...all(1), [p]: 0 } });
	for (const p of inputs)
		out.push({ inputs: { ...all(0), [p]: 1 } });
	return out;
}

/** 自动推断输出引脚：被门驱动的引脚；否则取非 unused 且未作为输入的引脚 */
export function inferOutputs(def: CustomSimComponent, vectors: TruthVector[]): string[] {
	if (def.gates?.length) {
		const pinIds = new Set(def.pins.map(p => p.id));
		return [...new Set(def.gates.map(g => g.output).filter(o => pinIds.has(o)))];
	}
	const inputs = new Set(vectors.flatMap(v => Object.keys(v.inputs ?? {})));
	return def.pins.filter(p => p.type !== 'unused' && !inputs.has(p.id)).map(p => p.id);
}

/** 自动推断输入引脚：门输入里出现的引脚 */
export function inferInputs(def: CustomSimComponent): string[] {
	const pinIds = new Set(def.pins.map(p => p.id));
	const outs = new Set((def.gates ?? []).map(g => g.output));
	const ins = (def.gates ?? []).flatMap(g => g.inputs).filter(n => pinIds.has(n) && !outs.has(n));
	return [...new Set(ins)].sort((a, b) => (def.pins.find(p => p.id === a)?.number ?? 0) - (def.pins.find(p => p.id === b)?.number ?? 0));
}

/**
 * 在引擎中运行真值表：一次加载全部向量的独立实例，运行 steps 步（默认 200µs 仿真时间）后读取探针电压。
 * 逻辑判定：≥ 3.5V 为 1，≤ 1.5V 为 0，其余为 X。
 */
export function runTruthTable(engine: SimEngine, def: CustomSimComponent, vectors: TruthVector[], outputs: string[], steps = 200): TruthResult {
	const list = vectors.slice(0, 256);
	engine.installCustom([def]);
	const tb = buildTestBench(def, list, outputs, 1);
	const r = engine.run(tb.circuit, steps);
	const rows: TruthRow[] = list.map(v => ({
		inputs: Object.fromEntries(Object.entries(v.inputs ?? {}).map(([k, x]) => [k, Number(x) ? 1 : 0])),
		outputs: {},
		expect: v.expect ? Object.fromEntries(Object.entries(v.expect).map(([k, x]) => [k, Number(x) ? 1 : 0])) : undefined,
	}));
	for (const p of tb.probes) {
		const s = r.stats.get(p.key);
		const volt = typeof s?.last === 'number' ? Math.round(s.last * 1000) / 1000 : undefined;
		const logic: 0 | 1 | 'X' = volt === undefined ? 'X' : volt >= 3.5 ? 1 : volt <= 1.5 ? 0 : 'X';
		rows[p.vector].outputs[p.pin] = { volt, logic };
	}
	let passed = 0;
	let checked = 0;
	for (const row of rows) {
		if (!row.expect)
			continue;
		checked++;
		row.pass = Object.entries(row.expect).every(([k, x]) => row.outputs[k]?.logic === x);
		if (row.pass)
			passed++;
	}
	const errors = [...r.errors];
	if (r.load !== 0)
		errors.unshift(`测试电路加载失败（返回 ${r.load}）`);
	if (!r.stats.size)
		errors.unshift('没有采集到任何探针数据：元件可能加载失败（检查引脚 ID 与子电路中的 Tunnel 名称是否一致）');
	return { rows, passed, checked, total: rows.length, errors: errors.slice(0, 12), simTimeUs: Math.round(r.timePs / 1e6) };
}

/** 由引擎 JS 源码创建模块工厂（Emscripten ES6 模块，通过 blob / data URL 动态导入） */
export async function factoryFromSource(source: string, createUrl?: (blob: Blob) => string | undefined): Promise<SimFactory> {
	const blob = new Blob([source], { type: 'text/javascript' });
	let url: string | undefined;
	try {
		url = createUrl?.(blob);
	}
	catch {}
	if (!url) {
		try {
			url = URL.createObjectURL(blob);
		}
		catch {}
	}
	if (!url)
		url = `data:text/javascript;base64,${btoa(unescape(encodeURIComponent(source)))}`;
	const mod = await import(/* @vite-ignore */ url);
	const f = mod?.default ?? mod;
	if (typeof f !== 'function')
		throw new TypeError('SimulIDE 模块工厂未找到');
	return f as SimFactory;
}

/** 读取自定义元件列表（存储于扩展用户配置，主线程与侧边栏共享） */
export function decodeCustomList(raw: unknown): CustomSimComponent[] {
	try {
		const v = typeof raw === 'string' ? JSON.parse(raw) : raw;
		return Array.isArray(v) ? v.filter(x => x && typeof x.name === 'string' && Array.isArray(x.pins) && typeof x.circuit === 'string') : [];
	}
	catch {
		return [];
	}
}
