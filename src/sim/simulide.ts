export interface SimBinding {
	/** EDA 中的位号（如 U1） */
	designator?: string;
	/** EDA 中器件名称（外壳型号，如 74HC00） */
	componentName?: string;
	/** 绑定的自定义元件名 */
	model: string;
}

export interface RewriteReport {
	replaced: Array<{ circId: string; newCircId: string; designator?: string; model: string; pinsMapped: number; matchedBy: string }>;
	unmatched: SimBinding[];
	warnings: string[];
}

/**
 * 把网表中绑定了自定义模型的外壳子电路改写为自定义元件：
 * CircId「74HC00-13」→「74HC30-13」，所有「74HC00-13-<外壳引脚ID>」按物理引脚号映射为「74HC30-13-<自定义引脚ID>」。
 */
export function rewriteNetlist(netlist: string, bindings: SimBinding[], customs: CustomSimComponent[], readShellPins: (shell: string) => Array<{ id: string }> | undefined): { netlist: string; report: RewriteReport } {
	const report: RewriteReport = { replaced: [], unmatched: [], warnings: [] };
	if (!bindings.length)
		return { netlist, report };
	const lines = netlist.split('\n');
	const subs: Array<{ idx: number; attrs: Record<string, string>; shell: string; num: string }> = [];
	lines.forEach((l, idx) => {
		if (!/^\s*<item\b/.test(l) || !/itemtype="Subcircuit"/.test(l))
			return;
		const attrs = parseAttrs(l);
		const cid = attrs.CircId ?? attrs.uid ?? '';
		const parts = cid.split('-');
		if (parts.length < 2)
			return;
		subs.push({ idx, attrs, shell: parts.slice(0, -1).join('-'), num: parts[parts.length - 1] });
	});
	const taken = new Set<number>();
	const pending = [...bindings];
	const apply = (b: SimBinding, s: typeof subs[number], by: string) => {
		const custom = customs.find(c => c.name === b.model);
		if (!custom) {
			report.warnings.push(`自定义元件 ${b.model} 不存在（${b.designator ?? s.attrs.CircId}）`);
			return;
		}
		const shellPins = readShellPins(s.shell);
		const oldCid = `${s.shell}-${s.num}`;
		const newCid = `${custom.name}-${s.num}`;
		taken.add(s.idx);
		lines[s.idx] = lines[s.idx].replace(`CircId="${oldCid}"`, `CircId="${newCid}"`).replace(/\sLogic_Symbol="[^"]*"/, '');
		let mapped = 0;
		if (!shellPins) {
			report.warnings.push(`未找到外壳 ${s.shell} 的封装文件，无法映射引脚`);
		}
		else {
			if (shellPins.length !== custom.pins.length)
				report.warnings.push(`外壳 ${s.shell} 有 ${shellPins.length} 个引脚，${custom.name} 有 ${custom.pins.length} 个，仅映射编号重合的引脚`);
			const map = new Map<string, string>();
			shellPins.forEach((sp, i) => {
				const cp = custom.pins.find(p => p.number === i + 1);
				if (cp && sp.id)
					map.set(`${oldCid}-${sp.id}`, `${newCid}-${cp.id}`);
			});
			const re = new RegExp(`"${oldCid.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}-([^"]+)"`, 'g');
			for (let i = 0; i < lines.length; i++) {
				if (!lines[i].includes(oldCid))
					continue;
				lines[i] = lines[i].replace(re, (m0, pin: string) => {
					const to = map.get(`${oldCid}-${pin}`);
					if (to) {
						mapped++;
						return `"${to}"`;
					}
					return m0;
				});
			}
		}
		report.replaced.push({ circId: oldCid, newCircId: newCid, designator: b.designator, model: custom.name, pinsMapped: mapped, matchedBy: by });
	};
	// 1) 按位号匹配：任一属性值等于位号
	for (const b of [...pending]) {
		if (!b.designator)
			continue;
		const s = subs.find(x => !taken.has(x.idx) && Object.entries(x.attrs).some(([k, v]) => k !== 'itemtype' && v.trim() === b.designator));
		if (s) {
			apply(b, s, 'designator');
			pending.splice(pending.indexOf(b), 1);
		}
	}
	// 2) 兜底：按外壳型号顺序匹配
	for (const b of [...pending]) {
		const name = (b.componentName ?? '').toUpperCase();
		const s = name ? subs.find(x => !taken.has(x.idx) && x.shell.toUpperCase() === name) : undefined;
		if (s) {
			apply(b, s, 'shell-name');
			pending.splice(pending.indexOf(b), 1);
		}
	}
	report.unmatched = pending;
	return { netlist: lines.join('\n'), report };
}

